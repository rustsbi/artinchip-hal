//! Blocking QSPI interface.

// Reference:
// - https://github.com/artinchip/luban-lite/blob/main/bsp/artinchip/hal/qspi/hal_qspi.c
// - https://aicdoc.artinchip.com/topics/ic/qspi/qspi-programming-guide-d13x.html

use super::bus::QuadSpiBus;
use super::config::*;
use super::error::QspiError;
use super::instance::Qspi;
use super::pad::*;
use super::register::*;

use crate::cmu::{ClockTree, Cmu};
use embedded_hal::spi::{MODE_1, MODE_3, Operation};

pub struct BlockingQspi<'a, const I: u8, PAD>
where
    PAD: QspiPads<I>,
{
    reg: &'a RegisterBlock,
    config: QspiConfig,
    /// SCK frequency produced by the divider chain.
    sck_hz: u32,
    pad: PAD,
}

/// QSPI internal clock divider selection.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum DividerSelect {
    /// CDR1 mode: sclk >> div.
    Cdr1(u8),
    /// CDR2 mode: sclk / (2 * (div + 1)).
    Cdr2(u8),
}

/// Byte counts for one half-duplex phase (`TBC`, `TWC`, `STXD`, `DMY_CNT`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct TransferCounts {
    /// `SPI_TBC`: total number of bytes transferred on the bus.
    total: u32,
    /// `SPI_TWC`: number of bytes read from the TX FIFO.
    tx: u32,
    /// `SPI_TMC.STXD_CNT`: number of bytes sent on one data line.
    single_line_tx: u32,
    /// `SPI_TMC.DMY_CNT`: dummy bytes generated by hardware instead of the CPU.
    hardware_dummy: u8,
}

impl TransferCounts {
    /// Counts for a transmit-only phase of `len` bytes.
    const fn tx(len: usize, single_line: bool) -> Self {
        Self {
            total: len as u32,
            tx: len as u32,
            single_line_tx: if single_line { len as u32 } else { 0 },
            hardware_dummy: 0,
        }
    }

    /// Counts for a receive-only phase of `len` bytes.
    const fn rx(len: usize) -> Self {
        Self {
            total: len as u32,
            tx: 0,
            single_line_tx: 0,
            hardware_dummy: 0,
        }
    }
}

impl<'a, const I: u8, PAD> BlockingQspi<'a, I, PAD>
where
    PAD: QspiPads<I>,
{
    const MAX_HZ: u32 = 100_000_000;
    const MIN_HZ: u32 = 100_000;
    const DEFAULT_TX_WATERMARK: u8 = 32;
    const DEFAULT_RX_WATERMARK: u8 = 32;
    const FIFO_DEPTH: u8 = 64;

    /// Create a new blocking QSPI interface.
    pub fn new(
        reg: &'a RegisterBlock,
        pad: PAD,
        config: QspiConfig,
        clock_tree: &ClockTree,
        cmu: &mut Cmu,
    ) -> Self {
        if config.mode == MODE_1 || config.mode == MODE_3 {
            panic!("QSPI only supports SPI modes 0 and 2");
        }

        let target_freq = config.freq.0.clamp(Self::MIN_HZ, Self::MAX_HZ);
        let pll_fra0_freq = clock_tree.pll_fra0.0;
        let (mod_div, divider) = Self::select_clock(pll_fra0_freq, target_freq);
        let sck_hz = Self::actual_sck(pll_fra0_freq, mod_div, divider);

        Self::enable_module_clock(cmu, mod_div);
        Self::configure_registers(reg, &config, divider, sck_hz, clock_tree.osc_24m.0);
        Self::init_fifos(reg);

        Self {
            reg,
            config,
            sck_hz,
            pad,
        }
    }

    fn enable_module_clock(cmu: &mut Cmu, mod_div: u8) {
        let clk = cmu.register_block();
        let qspi_clk = match I {
            0 => &clk.clock_qspi0,
            1 => &clk.clock_qspi1,
            2 => &clk.clock_qspi2,
            3 => &clk.clock_qspi3,
            _ => panic!("Invalid QSPI index"),
        };

        unsafe {
            // Configure and enable module clock.
            // Reference: https://aicdoc.artinchip.com/topics/ic/cmu/cmu-function2-d13x.html
            qspi_clk.modify(|v| {
                v.set_module_clk_div(mod_div)
                    .enable_module_clk()
                    .enable_bus_clk()
            });
            qspi_clk.modify(|v| v.enable_module_reset());
            riscv::asm::delay(500);
            qspi_clk.modify(|v| v.disable_module_reset());
        }
    }

    fn configure_registers(
        reg: &RegisterBlock,
        config: &QspiConfig,
        divider: DividerSelect,
        sck_hz: u32,
        osc_hz: u32,
    ) {
        let cs_ctrl_mode = if config.cs_config.is_some() {
            CsCtrlMode::SpiController
        } else {
            CsCtrlMode::Software
        };

        unsafe {
            // Software reset QSPI controller.
            reg.config.modify(|v| v.set_ctrl_rst(true));
            riscv::asm::delay(500);

            // Configure internal clock divider BEFORE enabling controller.
            reg.clk_config.modify(|v| match divider {
                DividerSelect::Cdr1(div) => v
                    .set_clock_divider_selection(ClockDivSel::Div1)
                    .set_clk_div_1(div),
                DividerSelect::Cdr2(div) => v
                    .set_clock_divider_selection(ClockDivSel::Div2)
                    .set_clk_div_2(div),
            });

            // Small delay to ensure clock config is latched.
            riscv::asm::delay(100);

            // Clear reset and enable controller.
            reg.config.modify(|v| {
                v.set_ctrl_mode(config.ctrl_mode)
                    .set_ctrl_rst(false) // Clear reset flag.
                    .enable_ctrl()
                    .enable_rx_full_stop()
            });

            // Disable all interrupts.
            reg.int_control.modify(|v| v.disable_all_int());

            reg.trans_config.modify(|v| {
                let v = v
                    .enable_discard_invalid_data()
                    .set_clk_pha(config.mode.phase)
                    .set_clk_pol(config.mode.polarity)
                    .set_cs_ctrl_mode(cs_ctrl_mode)
                    .enable_tx_data_delay();
                if config.lsb_first {
                    v.enable_lsb_transmit()
                } else {
                    v.disable_lsb_transmit()
                }
            });

            if let Some(cs_config) = config.cs_config {
                reg.trans_config.modify(|v| {
                    v.set_cs_pol(cs_config.polarity)
                        .set_cs_level(cs_config.level)
                        .set_cs_pin_num(cs_config.pin)
                });
            }

            // Configure RX sample delay based on frequency.
            if sck_hz <= osc_hz {
                reg.trans_config
                    .modify(|v| v.disable_rx_data_delay().disable_rx_inner_delay());
            } else {
                reg.trans_config
                    .modify(|v| v.enable_rx_data_delay().disable_rx_inner_delay());
            }

            // Configure bus mode.
            let bus_mode = if config.bit_mode_en {
                BusMode::StandardBits
            } else {
                BusMode::StandardBytes
            };
            // Configure work mode.
            match config.work_mode {
                WorkMode::Standard => {
                    reg.bit_mode_trans_config
                        .modify(|v| v.set_bus_mode(bus_mode));
                }
                WorkMode::ThreeWire => {
                    reg.bit_mode_trans_config
                        .modify(|v| v.set_bus_mode(bus_mode));
                    if !config.bit_mode_en {
                        reg.trans_config.modify(|v| v.enable_three_wire());
                    }
                }
                WorkMode::Dual | WorkMode::DualIO => {
                    reg.trans_misc_control.modify(|v| v.enable_dual());
                }
                WorkMode::Quad | WorkMode::QuadIO => {
                    reg.trans_misc_control.modify(|v| v.enable_quad());
                }
                WorkMode::Qpi => {
                    // QPI exists only on the v1.1 QSPI controller revisions
                    // (D13x/G73x). D21x's v1.0 controller has no QPI bit.
                    #[cfg(any(feature = "d13x", feature = "g73x"))]
                    reg.trans_misc_control.modify(|v| v.enable_qpi());
                    #[cfg(not(any(feature = "d13x", feature = "g73x")))]
                    panic!("QPI mode is not supported by this QSPI controller revision");
                }
            }
        }
    }

    /// Reset both FIFOs, set watermarks, and clear stale interrupt status.
    fn init_fifos(reg: &RegisterBlock) {
        unsafe {
            reg.fifo_control.modify(|v| {
                v.reset_tx_fifo()
                    .reset_rx_fifo()
                    .set_tx_fifo_water_mark(Self::DEFAULT_TX_WATERMARK)
                    .set_rx_fifo_water_mark(Self::DEFAULT_RX_WATERMARK)
            });

            // Wait for FIFO reset to complete.
            riscv::asm::delay(100);

            // Clear all interrupt status.
            reg.int_status.modify(|v| v.clear_all_int());
        }
    }

    /// SCK frequency produced by the divider chain.
    pub const fn sck_hz(&self) -> u32 {
        self.sck_hz
    }

    /// Configuration this bus was built with.
    pub const fn config(&self) -> QspiConfig {
        self.config
    }

    /// Dummy bytes the command/address phase needs for `tclqv_ns` at the
    /// programmed SCK, rounded up to whole single-line bytes, plus `margin`.
    pub fn dummy_bytes_for(&self, tclqv_ns: u32, margin: u8) -> u8 {
        let bits = (u64::from(tclqv_ns) * u64::from(self.sck_hz)).div_ceil(1_000_000_000);
        let bytes = bits.div_ceil(8) as u8;
        let total = bytes.saturating_add(margin);
        if bits == 0 && margin == 0 {
            0
        } else {
            total.max(1)
        }
    }

    fn actual_sck(pll_hz: u32, mod_div: u8, divider: DividerSelect) -> u32 {
        let module = pll_hz / (u32::from(mod_div) + 1);
        match divider {
            DividerSelect::Cdr1(div) => module >> u32::from(div),
            DividerSelect::Cdr2(div) => module / (2 * (u32::from(div) + 1)),
        }
    }

    pub(super) fn quad_read_start(
        &mut self,
        command: &[u8],
        tclqv_ns: u32,
        margin: u8,
    ) -> Result<(), QspiError> {
        let dummy = usize::from(self.dummy_bytes_for(tclqv_ns, margin));
        let mut frame = [0u8; 16];
        let command_len = command.len().min(frame.len() - dummy.min(8));
        frame[..command_len].copy_from_slice(&command[..command_len]);
        let total = command_len + dummy.min(8);
        self.tx_phase(&frame[..total], true)?;
        self.set_work_mode(WorkMode::Quad)
    }

    pub(super) fn quad_read_end(&mut self) -> Result<(), QspiError> {
        self.set_work_mode(WorkMode::Standard)
    }

    pub(super) fn quad_write_start(&mut self, command: &[u8]) -> Result<(), QspiError> {
        self.tx_command(command)?;
        self.set_work_mode(WorkMode::Quad)
    }

    pub(super) fn quad_write_end(&mut self) -> Result<(), QspiError> {
        self.set_work_mode(WorkMode::Standard)
    }

    /// Read `data` with a quad data phase (`command` on one line, dummy bytes, then four-line data).
    pub fn read_quad(
        &mut self,
        command: &[u8],
        tclqv_ns: u32,
        margin: u8,
        data: &mut [u8],
    ) -> Result<(), QspiError> {
        self.quad_read_start(command, tclqv_ns, margin)?;
        let result = self.rx_phase(data);
        self.quad_read_end()?;
        result
    }

    /// Write `data` with a quad data phase (`command` on one line, then four-line payload).
    pub fn write_quad(&mut self, command: &[u8], data: &[u8]) -> Result<(), QspiError> {
        self.quad_write_start(command)?;
        let result = self.tx_phase(data, false);
        self.quad_write_end()?;
        result
    }

    /// Reset the TX and RX FIFOs before a new transfer.
    fn reset_fifos(&mut self) {
        unsafe {
            self.reg
                .fifo_control
                .modify(|v| v.reset_tx_fifo().reset_rx_fifo());
            riscv::asm::delay(10);
        }
    }

    pub(super) fn tx_data_addr(&self) -> u32 {
        core::ptr::addr_of!(self.reg.tx_data) as u32
    }

    pub(super) fn rx_data_addr(&self) -> u32 {
        core::ptr::addr_of!(self.reg.rx_data) as u32
    }

    pub(super) fn prepare_rx_dma(&mut self, len: usize) {
        self.reset_fifos();
        self.program_transfer(TransferCounts::rx(len));
        unsafe {
            self.reg.fifo_control.modify(|v| v.enable_rx_fifo_dma_req());
        }
    }

    pub(super) fn prepare_tx_dma(&mut self, len: usize, single_line: bool) {
        self.reset_fifos();
        self.program_transfer(TransferCounts::tx(len, single_line));
        unsafe {
            self.reg.fifo_control.modify(|v| v.enable_tx_fifo_dma_req());
        }
    }

    pub(super) fn finish_dma(&mut self) {
        unsafe {
            self.reg
                .fifo_control
                .modify(|v| v.disable_rx_fifo_dma_req().disable_tx_fifo_dma_req());
        }
    }

    fn program_transfer(&mut self, counts: TransferCounts) {
        unsafe {
            self.reg
                .total_bytes_cnt
                .modify(|v| v.set_total_bytes(counts.total));
            self.reg.trans_write_cnt.modify(|v| v.set_tx_cnt(counts.tx));
            self.reg.trans_misc_control.modify(|v| {
                v.set_single_tx_count(counts.single_line_tx)
                    .set_dummy_count(counts.hardware_dummy)
            });
        }
    }

    /// Start a new transfer.
    pub(super) fn start_transfer(&mut self) {
        unsafe { self.reg.trans_config.modify(|v| v.set_start(true)) };
    }

    fn begin_transfer(&mut self, counts: TransferCounts) {
        self.program_transfer(counts);
        self.start_transfer();
    }

    /// Wait for the transfer to complete.
    pub(super) fn wait_transfer_done(&mut self) -> Result<(), QspiError> {
        let mut timeout = 100_000;
        while self.reg.trans_config.read().start() {
            timeout -= 1;
            if timeout == 0 {
                return Err(QspiError::Timeout);
            }
            core::hint::spin_loop();
        }
        Ok(())
    }

    /// Wait until the TX FIFO has drained into the shifter.
    fn wait_tx_drained(&mut self) -> Result<(), QspiError> {
        let mut timeout = 100_000;
        while self.reg.fifo_status.read().tx_fifo_count() != 0 {
            timeout -= 1;
            if timeout == 0 {
                return Err(QspiError::Timeout);
            }
            core::hint::spin_loop();
        }
        Ok(())
    }

    fn tx_phase(&mut self, data: &[u8], single_line: bool) -> Result<(), QspiError> {
        if data.is_empty() {
            return Ok(());
        }
        let counts = TransferCounts::tx(data.len(), single_line);
        self.reset_fifos();
        self.begin_transfer(counts);
        self.write_bytes(data)?;
        self.wait_tx_drained()?;
        self.wait_transfer_done()
    }

    fn tx_command(&mut self, data: &[u8]) -> Result<(), QspiError> {
        self.tx_phase(data, true)
    }

    fn rx_phase(&mut self, data: &mut [u8]) -> Result<(), QspiError> {
        if data.is_empty() {
            return Ok(());
        }
        self.reset_fifos();
        self.begin_transfer(TransferCounts::rx(data.len()));
        self.read_bytes(data)?;
        self.wait_transfer_done()
    }

    /// Write bytes to the TX FIFO.
    fn write_bytes(&mut self, buf: &[u8]) -> Result<(), QspiError> {
        let tx = core::ptr::addr_of!(self.reg.tx_data) as *const u8 as *mut u8;
        let mut idx = 0usize;

        while idx < buf.len() {
            let mut timeout = 100_000;
            let room = loop {
                let used = self.reg.fifo_status.read().tx_fifo_count() as usize;
                let free = (Self::FIFO_DEPTH as usize).saturating_sub(used);
                if free > 0 {
                    break free;
                }
                timeout -= 1;
                if timeout == 0 {
                    return Err(QspiError::Timeout);
                }
                core::hint::spin_loop();
            };

            let len = core::cmp::min(room, buf.len() - idx);
            for &byte in &buf[idx..idx + len] {
                unsafe {
                    tx.write_volatile(byte);
                }
            }
            idx += len;
        }
        Ok(())
    }

    /// Read bytes from the RX FIFO.
    fn read_bytes(&self, buf: &mut [u8]) -> Result<(), QspiError> {
        if buf.is_empty() {
            return Ok(());
        }

        let rx = core::ptr::addr_of!(self.reg.rx_data) as *const u8;
        let mut idx = 0usize;

        while idx < buf.len() {
            let mut timeout = 100_000;
            let len = loop {
                let available = self.reg.fifo_status.read().rx_fifo_count() as usize;
                if available > 0 {
                    break core::cmp::min(available, buf.len() - idx);
                }
                timeout -= 1;
                if timeout == 0 {
                    return Err(QspiError::Timeout);
                }
                core::hint::spin_loop();
            };

            for byte in &mut buf[idx..idx + len] {
                *byte = unsafe { rx.read_volatile() };
            }
            idx += len;
        }
        Ok(())
    }

    /// Select the module and internal dividers with the smallest frequency
    /// error. Ties prefer a clock at or below the requested frequency.
    fn select_clock(pll_fra0: u32, target: u32) -> (u8, DividerSelect) {
        let mut best_error = u32::MAX;
        let mut best_over = true;
        let mut best_mod_div = 0;
        let mut best_divider = DividerSelect::Cdr1(0);

        // CDR1: SCK = module / 2^cdr1.
        // CDR2: SCK = module / (2 * (cdr2 + 1)).
        for mod_div in 0..=0x1F {
            let module = pll_fra0 / (mod_div as u32 + 1);
            if module == 0 || module > Self::MAX_HZ {
                continue;
            }

            for cdr1 in 0..=0xF {
                let actual = module >> cdr1;
                let error = actual.abs_diff(target);
                let over = actual > target;
                if error < best_error || (error == best_error && !over && best_over) {
                    best_error = error;
                    best_over = over;
                    best_mod_div = mod_div;
                    best_divider = DividerSelect::Cdr1(cdr1);
                }
            }

            for cdr2 in 0..=0xFF {
                let actual = module / (2 * (cdr2 as u32 + 1));
                let error = actual.abs_diff(target);
                let over = actual > target;
                if error < best_error || (error == best_error && !over && best_over) {
                    best_error = error;
                    best_over = over;
                    best_mod_div = mod_div;
                    best_divider = DividerSelect::Cdr2(cdr2);
                }
            }
        }

        (best_mod_div, best_divider)
    }

    /// Switch the data-line width used by subsequent transfers.
    pub fn set_work_mode(&mut self, mode: WorkMode) -> Result<(), QspiError> {
        self.wait_transfer_done()?;
        unsafe {
            match mode {
                WorkMode::Standard | WorkMode::ThreeWire => {
                    self.reg
                        .trans_misc_control
                        .modify(|v| v.disable_quad().disable_dual());
                    if mode == WorkMode::ThreeWire {
                        self.reg.trans_config.modify(|v| v.enable_three_wire());
                    } else {
                        self.reg.trans_config.modify(|v| v.disable_three_wire());
                    }
                }
                WorkMode::Dual | WorkMode::DualIO => {
                    self.reg
                        .trans_misc_control
                        .modify(|v| v.disable_quad().enable_dual());
                    self.reg.trans_config.modify(|v| v.disable_three_wire());
                }
                WorkMode::Quad | WorkMode::QuadIO => {
                    self.reg
                        .trans_misc_control
                        .modify(|v| v.enable_quad().disable_dual());
                    self.reg.trans_config.modify(|v| v.disable_three_wire());
                }
                WorkMode::Qpi => self.set_qpi_mode()?,
            }
        }
        Ok(())
    }

    fn set_qpi_mode(&mut self) -> Result<(), QspiError> {
        #[cfg(any(feature = "d13x", feature = "g73x"))]
        {
            unsafe {
                self.reg
                    .trans_misc_control
                    .modify(|v| v.enable_quad().enable_qpi());
            }
            Ok(())
        }
        #[cfg(not(any(feature = "d13x", feature = "g73x")))]
        {
            Err(QspiError::Unsupported)
        }
    }

    /// Free the blocking QSPI and return QSPI instance and all pads.
    pub fn free(self, cmu: &mut Cmu) -> (Qspi<I>, PAD) {
        let clk = cmu.register_block();
        let qspi_clk = match I {
            0 => &clk.clock_qspi0,
            1 => &clk.clock_qspi1,
            2 => &clk.clock_qspi2,
            _ => &clk.clock_qspi3,
        };

        // Disable clock and reset module.
        unsafe {
            qspi_clk.modify(|v| {
                v.disable_module_clk()
                    .disable_bus_clk()
                    .enable_module_reset()
            });
        }

        (Qspi::<I>::__new(self.reg as *const RegisterBlock), self.pad)
    }
}

impl<'a, const I: u8, PAD> embedded_hal::spi::ErrorType for BlockingQspi<'a, I, PAD>
where
    PAD: QspiPads<I>,
{
    type Error = QspiError;
}

impl<'a, const I: u8, PAD> embedded_hal::spi::SpiBus for BlockingQspi<'a, I, PAD>
where
    PAD: QspiPads<I>,
{
    fn read(&mut self, words: &mut [u8]) -> Result<(), Self::Error> {
        self.rx_phase(words)
    }

    fn write(&mut self, words: &[u8]) -> Result<(), Self::Error> {
        self.tx_command(words)
    }

    fn transfer(&mut self, read: &mut [u8], write: &[u8]) -> Result<(), Self::Error> {
        if !write.is_empty() {
            self.tx_command(write)?;
        }
        if !read.is_empty() {
            self.rx_phase(read)?;
        }
        Ok(())
    }

    fn transfer_in_place(&mut self, words: &mut [u8]) -> Result<(), Self::Error> {
        let mut temp = [0u8; 256];
        for chunk in words.chunks_mut(256) {
            let len = chunk.len();
            temp[..len].copy_from_slice(chunk);
            <Self as embedded_hal::spi::SpiBus>::transfer(self, chunk, &temp[..len])?;
        }
        Ok(())
    }

    fn flush(&mut self) -> Result<(), Self::Error> {
        self.wait_transfer_done()
    }
}

impl<'a, const I: u8, PAD> embedded_hal::spi::SpiDevice for BlockingQspi<'a, I, PAD>
where
    PAD: QspiPads<I>,
{
    fn transaction(&mut self, operations: &mut [Operation<'_, u8>]) -> Result<(), Self::Error> {
        for op in operations.iter_mut() {
            match op {
                Operation::Write(buf) => {
                    self.tx_command(buf)?;
                }
                Operation::Read(buf) => {
                    self.rx_phase(buf)?;
                }
                Operation::Transfer(read, write) => {
                    <Self as embedded_hal::spi::SpiBus>::transfer(self, read, write)?;
                }
                Operation::TransferInPlace(buf) => {
                    <Self as embedded_hal::spi::SpiBus>::transfer_in_place(self, buf)?;
                }
                Operation::DelayNs(ns) => {
                    riscv::asm::delay(*ns / 2);
                }
            }
        }
        Ok(())
    }
}

impl<'a, const I: u8, PAD> QuadSpiBus for BlockingQspi<'a, I, PAD>
where
    PAD: QspiPads<I>,
{
    fn read_quad(
        &mut self,
        command: &[u8],
        tclqv_ns: u32,
        margin: u8,
        data: &mut [u8],
    ) -> Result<(), Self::Error> {
        BlockingQspi::read_quad(self, command, tclqv_ns, margin, data)
    }

    fn write_quad(&mut self, command: &[u8], data: &[u8]) -> Result<(), Self::Error> {
        BlockingQspi::write_quad(self, command, data)
    }
}

