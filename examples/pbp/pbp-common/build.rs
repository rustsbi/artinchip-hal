//! Reads `boards/*.toml` and generates the bootloader slot constants (`layout.rs`)
//! so `pbp-common` never duplicates addresses or image names from the board preset.

use std::{env, fmt::Write as _, fs, path::Path};

use aicfwc::preset::{Chip, ComponentKind, Media, Preset};

fn main() {
    println!("cargo:rustc-link-arg=-Tartinchip-pbp.ld");

    let chip = if env::var("CARGO_FEATURE_D21X").is_ok() {
        Chip::D21x
    } else {
        Chip::D13x
    };
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set");
    let boards_dir =
        aicfwc::preset::boards_dir_from(Path::new(&manifest_dir)).unwrap_or_else(|| {
            panic!("no board preset directory (`boards/`) found above {manifest_dir}")
        });
    let preset = Preset::for_chip(&boards_dir, chip).unwrap_or_else(|error| {
        panic!(
            "failed to load the board preset for chip {}: {error:#}",
            chip.name()
        )
    });
    println!("cargo:rerun-if-changed={}", preset.path.display());
    println!("cargo:rerun-if-changed={}", boards_dir.display());

    let bootloader = preset
        .components
        .iter()
        .find(|component| component.kind == ComponentKind::App)
        .unwrap_or_else(|| {
            panic!(
                "board preset {} declares no boot-chain `kind = \"app\"` component",
                preset.path.display()
            )
        });
    let ram_slot = bootloader.ram.unwrap_or_else(|| {
        panic!(
            "board preset {} declares no `ram` slot on boot-chain component {:?}",
            preset.path.display(),
            bootloader.name
        )
    });
    let flash_offset = match preset.image.media {
        Media::SpiNor => 0u32,
        Media::SpiNand => parse_nand_page_size(&preset.image.media_id).unwrap_or(2048),
    };

    let mut out = String::from("// @generated by build.rs from the board preset -- do not edit.\n");
    let _ = writeln!(out, "pub const UPG_BOOTLOADER_SLOT: u32 = {ram_slot:#x};");
    let _ = writeln!(
        out,
        "pub const BOOTLOADER_APP_NAME: &str = {:?};",
        bootloader.name
    );
    let _ = writeln!(
        out,
        "pub const BOOTLOADER_FLASH_OFFSET: u32 = {flash_offset:#x};"
    );

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is always set");
    fs::write(Path::new(&out_dir).join("layout.rs"), out)
        .expect("failed to write generated pbp-common layout.rs");
}

/// Extract the page size in bytes from `media_id` strings such as `"P=2K,B=128K"`.
fn parse_nand_page_size(media_id: &str) -> Option<u32> {
    for token in media_id.split(',') {
        let Some(rest) = token.trim().strip_prefix("P=") else {
            continue;
        };
        if let Some(kib) = rest.strip_suffix(['K', 'k']) {
            return kib.parse::<u32>().ok()?.checked_mul(1024);
        }
        return rest.parse::<u32>().ok();
    }
    None
}
