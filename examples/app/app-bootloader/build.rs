//! Reads the board preset (`boards/*.toml`) and forwards link address, image name,
//! and generated partition constants to `app-bootloader`.

use std::{env, fmt::Write as _, fs, path::Path};

use aicfwc::preset::{Chip, ComponentKind, Preset};

fn main() {
    println!("cargo:rustc-link-arg=-Tartinchip-app.ld");

    let chip = if env::var("CARGO_FEATURE_D21X").is_ok() {
        Chip::D21x
    } else {
        Chip::D13x
    };
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set");
    let boards_dir = aicfwc::preset::boards_dir_from(Path::new(&manifest_dir)).unwrap_or_else(|| {
        panic!(
            "no board preset directory (`boards/`) found above {manifest_dir}; the bootloader's \
             flash layout and link address come from the board preset"
        )
    });
    let preset = Preset::for_chip(&boards_dir, chip).unwrap_or_else(|error| {
        panic!(
            "failed to load the board preset for chip {}: {error:#}",
            chip.name()
        )
    });
    println!("cargo:rerun-if-changed={}", preset.path.display());
    println!("cargo:rerun-if-changed={}", boards_dir.display());

    let base = preset.boot_chain_app_base().unwrap_or_else(|error| {
        panic!(
            "board preset {} cannot describe the bootloader: {error:#}",
            preset.path.display()
        )
    });
    let app_name = preset
        .components
        .iter()
        .find(|component| component.kind == ComponentKind::App)
        .map(|component| component.name.as_str())
        .unwrap_or("bootloader");

    println!("cargo:rustc-env=AIC_APP_NAME={app_name}");
    println!("cargo:rustc-link-arg=--defsym=APP_BASE={base:#x}");

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is always set");
    fs::write(Path::new(&out_dir).join("partitions.rs"), generate(&preset))
        .expect("failed to write the generated partition table");
}

fn generate(preset: &Preset) -> String {
    let mut out = String::from(
        "// @generated by build.rs from the board preset -- do not edit.\n\
         /// On-flash layout declared by `[[partition]]` in the board preset.\n\
         pub const FLASH_LAYOUT: &[Partition] = &[\n",
    );
    for partition in &preset.partitions {
        let _ = writeln!(
            out,
            "    Partition {{ name: {:?}, offset: {:#x}, size: {:#x} }},",
            partition.name, partition.offset, partition.size
        );
    }
    out.push_str("];\n\n");

    let mut table = String::from("mtd=spi0.0:");
    for (index, partition) in preset.partitions.iter().enumerate() {
        if index > 0 {
            table.push(',');
        }
        let _ = write!(table, "{}({})", human_size(partition.size), partition.name);
    }
    let _ = writeln!(out, "/// Partition table string reported to the host.");
    let _ = writeln!(out, "pub const PARTITION_TABLE: &str = {table:?};");

    let _ = writeln!(
        out,
        "\n/// App name a normal boot jumps to (`[image] app`); empty boots any valid\n\
         /// image in the `app` partition.\n\
         pub const BOOT_APP: &str = {:?};",
        preset.image.boot_app
    );
    out
}

fn human_size(bytes: u32) -> String {
    if bytes.is_multiple_of(1024 * 1024) {
        format!("{}m", bytes / (1024 * 1024))
    } else if bytes.is_multiple_of(1024) {
        format!("{}k", bytes / 1024)
    } else {
        bytes.to_string()
    }
}
